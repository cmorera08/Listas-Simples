    public void imprimir(){
        Cliente aux = met.inicio;
        listModel.clear();//Limpió el listModel
        while(aux!=null){
            listModel.addElement(aux.nombre);//Lleno el listModel
            listModel.addElement(""+aux.edad);
            listModel.addElement(""+aux.cedula);
            listModel.addElement(aux.provincia);
            aux=aux.sig;
        }
        jList1.setModel(listModel);  
    }
    
